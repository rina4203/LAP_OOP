package ua.lab.coffeevan.model;

/**
 * Значення з кодом і назвою українською мовою: сорт, упаковка,
 * ступінь обсмаження тощо.
 *
 * <p>Інтерфейс реалізують переліки моделі, тож підказки для користувача
 * можна будувати однаково, не знаючи конкретного переліку.
 *
 * @author rina4203
 * @version 1.0
 */
public interface DisplayNamed {

    /**
     * Повертає код значення, як він записується у файлах,
     * наприклад {@code "PAPER_BAG"}.
     *
     * @return код значення
     */
    String name();

    /**
     * Повертає назву значення українською мовою.
     *
     * @return назва значення
     */
    String getDisplayName();
}
